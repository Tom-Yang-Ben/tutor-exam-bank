/**
 * 章節名 → 它所屬的學科（章節名在三科白名單內是唯一的，第 6.1 條；〔stage5 WS-B〕加入化學後仍唯一，單元測試釘住）。
 * @type {Map<string, string>}
 */
const SUBJECT_OF_CHAPTER = new Map();
for (const [subject, list] of Object.entries(CHAPTERS)) {
    for (const chapter of list) SUBJECT_OF_CHAPTER.set(chapter, subject);
}

/** 組裝 { [別名]: 章節 }；重複鍵會被靜默覆寫，因此另外記下來給單元測試斷言。 */
const CHAPTER_ALIASES = {};
const DUPLICATE_ALIASES = [];
let aliasCount = 0;
for (const [chapter, list] of Object.entries(ALIASES_BY_CHAPTER)) {
    for (const alias of list) {
        aliasCount += 1;
        if (Object.prototype.hasOwnProperty.call(CHAPTER_ALIASES, alias)) {
            DUPLICATE_ALIASES.push({ alias, kept: CHAPTER_ALIASES[alias], dropped: chapter });
            continue;
        }
        CHAPTER_ALIASES[alias] = chapter;
    }
}

/**
 * 別名總數（含重複）——單元測試拿它與 Object.keys(CHAPTER_ALIASES).length 對照，
 * 兩者不等就代表有鍵被覆寫掉了。
 * @type {number}
 */
const ALIAS_COUNT = aliasCount;

/**
 * 由章節反推學科。
 * @param {string} chapter
 * @returns {string|null} '數學'｜'物理'｜'化學'；不在白名單內時回 null
 */
function subjectOfChapter(chapter) {
    return SUBJECT_OF_CHAPTER.get(chapter) || null;
}

/**
 * 檢查別名表的三條硬規則（第 6.2 條）。單元測試與載入端共用同一支，
 * 不讓「測試裡另寫一份檢查」與實際規則慢慢分岔。
 * @returns {string[]} 問題描述；空陣列 = 全數通過
 */
function validateAliases(table = CHAPTER_ALIASES) {
    const problems = [];

    // ① 值必須是白名單章節
    for (const [alias, chapter] of Object.entries(table)) {
        const subject = subjectOfChapter(chapter);
        if (!subject || !isValidChapter(subject, chapter)) {
            problems.push(`別名「${alias}」對到的章節「${chapter}」不在任何一科的白名單內`);
        }
        if (alias.trim() === '') problems.push('有一個別名是空字串');
    }

    // ② 重複鍵（由 ALIASES_BY_CHAPTER 組裝時記下）
    for (const d of DUPLICATE_ALIASES) {
        problems.push(`別名「${d.alias}」重複：先對到「${d.kept}」，又對到「${d.dropped}」`);
    }

    // ③ 沒有別名是另一個別名的子字串卻對到不同章節
    const entries = Object.entries(table);
    for (const [shortAlias, shortChapter] of entries) {
        for (const [longAlias, longChapter] of entries) {
            if (shortAlias === longAlias) continue;
            if (shortChapter === longChapter) continue;
            if (longAlias.includes(shortAlias)) {
                problems.push(
                    `別名「${shortAlias}」（→${shortChapter}）是別名「${longAlias}」（→${longChapter}）的子字串，` +
                    '「長的優先」會變成歧義規則'
                );
            }
        }
    }

    // ③' 別名不得等於「別章」的章節本名：parseQuery 會同時比對章節本名與別名，
    //     兩張表撞在同一個字串上時，同一個詞會依掃描順序對到不同章節。
    for (const [alias, chapter] of entries) {
        const own = subjectOfChapter(alias);
        if (own && alias !== chapter) {
            problems.push(`別名「${alias}」本身就是章節白名單裡的章節名，卻對到「${chapter}」`);
        }
    }

    return problems;
}

/**
 * 每一章至少幾個別名（第 6.2 條要求 ≥ 3）。
 * @returns {Array<{chapter:string, count:number}>} 不足的章節
 */
function chaptersWithTooFewAliases(min = 3) {
    const out = [];
    for (const [subject, list] of Object.entries(CHAPTERS)) {
        for (const chapter of list) {
            const count = (ALIASES_BY_CHAPTER[chapter] || []).length;
            if (count < min) out.push({ subject, chapter, count });
        }
    }
    return out;
}

